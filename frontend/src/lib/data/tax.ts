/** Tarif efektif TER bulanan untuk bruto & kategori PTKP. */
export function terRateFor(grossMonthly: number, category: TERCategory = 'A'): number {
	for (const [limit, rate] of TABLES[category]) {
		if (grossMonthly <= limit) return rate;
	}
	return 0.34;
}

